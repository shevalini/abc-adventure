// Helper: get letter data by id
export const getLetterById = (id) =>
  alphabetData.find((l) => l.id === id?.toLowerCase()) || null;

// Helper: get adjacent letters
export const getAdjacentLetters = (id) => {
  const idx = alphabetData.findIndex((l) => l.id === id?.toLowerCase());
  if (idx === -1) return { prev: null, next: null };
  return {
    prev: idx > 0 ? alphabetData[idx - 1] : null,
    next: idx < alphabetData.length - 1 ? alphabetData[idx + 1] : null,
  };
};
